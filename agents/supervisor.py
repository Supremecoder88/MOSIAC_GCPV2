
import uuid
import json

from langchain_openai import ChatOpenAI
from langchain_core.messages import HumanMessage, SystemMessage

from graph.state import MosaicState, SignalOutput
from config.settings import settings
from config.logging_config import setup_logging


logger = setup_logging(__name__)

llm = ChatOpenAI(
    model=settings.openai_chat_model,
    temperature=0.1,
    api_key=settings.openai_api_key,
)


async def supervisor_route(state: MosaicState) -> dict:
    """Initialize the analysis run."""

    run_id = str(uuid.uuid4())

    logger.info(
        f"Supervisor routing | "
        f"run_id={run_id} | "
        f"task='{state.get('task', '')[:80]}'"
    )

    return {
        "run_id": run_id,
        "agents_activated": [],
        "signals": [],
        "run_complete": False,
        "error_log": [],
    }


async def supervisor_compile(state: MosaicState) -> dict:
    """Compile agent signals into an evidence-grounded intelligence brief."""

    signals = state.get("signals", [])
    agents_activated = list(dict.fromkeys(
        state.get("agents_activated", [])
    ))
    task = state.get("task", "")
    error_log = state.get("error_log", [])

    logger.info(
        f"Supervisor compiling brief | "
        f"signals={len(signals)} | "
        f"agents_activated={len(agents_activated)}"
    )

    high_confidence_signals = [
        signal
        for signal in signals
        if signal.get("confidence", 0) >= 0.6
    ]

    review_signals = [
        signal
        for signal in signals
        if signal.get("confidence", 0) < 0.6
    ]

    if not signals:
        final_brief = (
            "**EXECUTIVE SUMMARY**\n\n"
            "Analysis completed. No research integrity signals "
            "were generated by the activated agents for this study.\n\n"
            "**PIPELINE HEALTH**\n\n"
            f"Agents activated: {len(agents_activated)} of 6.\n"
            f"Recorded errors: {len(error_log)}.\n\n"
            "No signal does not necessarily establish that a study "
            "has no research integrity issues. Some checks may be "
            "limited by unavailable or incomplete source data."
        )

        return {
            "final_brief": final_brief,
            "run_complete": True,
            "total_signals": 0,
            "signals_requiring_review": 0,
        }

    signals_text = _format_signals_for_llm(signals)

    errors_text = (
        json.dumps(error_log, indent=2, default=str)
        if error_log
        else "No errors were recorded in the graph state."
    )

    system_prompt = """
You are the Chief Intelligence Officer of MOSAIC,
a clinical-trial research-integrity analysis system.

Your task is to compile a professional intelligence brief
using ONLY the evidence supplied by specialist agents.

STRICT EVIDENCE RULES:

1. NEVER invent sponsor names, organizations, dates, trial results,
   adverse-event counts, or regulatory violations.

2. Use a sponsor name only when it explicitly appears in the
   supplied signal evidence.

3. If the sponsor is not present in the evidence, write
   "Sponsor information not available in the supplied evidence."
   Do not call the sponsor undisclosed.

4. A missing results posting may be reported as a transparency
   concern, but do not automatically describe it as a confirmed
   regulatory violation.

5. Missing adverse-event counts must never be interpreted as zero.

6. Do not claim a safety reporting gap unless the supplied evidence
   establishes a discrepancy between official registry data and
   published data.

7. Do not claim that historical amendments were unchanged or that
   no amendments occurred when amendment history is unavailable.

8. Distinguish verified findings from uncertainty and unavailable data.

9. Do not describe the entire pipeline as fully healthy merely
   because the agents completed execution.

10. If evidence is insufficient, explicitly say so.

11. Do not turn recommendations or hypotheses into established facts.

BRIEF FORMAT:

1. EXECUTIVE SUMMARY
2. SIGNALS BY PRIORITY
3. SIGNALS REQUIRING HUMAN REVIEW
4. PIPELINE HEALTH
5. DATA LIMITATIONS

For every signal include:
- What was found
- Supporting evidence
- Why it matters
- Recommended action

For pipeline health:
- Mention the number of activated agents.
- Mention recorded errors.
- Identify unavailable checks only when supported by supplied evidence.

TONE:
Professional, factual, cautious, and actionable.

The evidence supplied by agents takes priority over assumptions.
If information is missing, say that it is missing.
"""

    human_prompt = f"""
ANALYSIS TASK:
{task}

AGENT SIGNALS AND SUPPORTING EVIDENCE:
{signals_text}

SIGNAL STATISTICS:
Total signals: {len(signals)}
High-confidence signals: {len(high_confidence_signals)}
Signals requiring human review: {len(review_signals)}

AGENTS ACTIVATED:
{', '.join(agents_activated)}

RECORDED GRAPH ERRORS:
{errors_text}

Prepare the final intelligence brief.

Do not introduce facts that are absent from the supplied evidence.
"""

    try:
        response = await llm.ainvoke([
            SystemMessage(content=system_prompt),
            HumanMessage(content=human_prompt),
        ])

        final_brief = response.content

        logger.info(
            f"Brief compiled successfully | "
            f"signals_included={len(signals)}"
        )

    except Exception as e:
        logger.error(
            f"LLM brief compilation failed | error={e}"
        )

        final_brief = _fallback_brief(
            signals,
            agents_activated,
            task,
            error_log,
        )

    return {
        "final_brief": final_brief,
        "run_complete": True,
        "total_signals": len(signals),
        "signals_requiring_review": len(review_signals),
    }


def _format_signals_for_llm(
    signals: list[SignalOutput]
) -> str:

    if not signals:
        return "No signals generated."

    lines = []

    for i, signal in enumerate(signals, start=1):
        lines.append(f"SIGNAL {i}:")
        lines.append(
            f"  Agent: {signal.get('agent', 'unknown')}"
        )
        lines.append(
            f"  Type: {signal.get('signal_type', 'unknown')}"
        )
        lines.append(
            f"  NCT ID: {signal.get('nct_id', 'N/A')}"
        )
        lines.append(
            f"  Confidence: "
            f"{signal.get('confidence', 0.0):.2f}"
        )
        lines.append(
            f"  Summary: {signal.get('summary', '')}"
        )

        evidence = signal.get("evidence", [])

        lines.append("  Supporting evidence:")

        if evidence:
            lines.append(
                json.dumps(evidence, indent=4, default=str)
            )
        else:
            lines.append("    No supporting evidence supplied.")

        lines.append("")

    return "\n".join(lines)


def _fallback_brief(
    signals: list,
    agents_activated: list,
    task: str,
    error_log: list | None = None,
) -> str:

    lines = [
        "**EXECUTIVE SUMMARY:**",
        f"Analysis complete. {len(signals)} signal(s) detected.",
        "",
        "**SIGNALS BY PRIORITY:**",
        "",
    ]

    for i, signal in enumerate(signals, start=1):
        lines.append(
            f"{i}. **{signal.get('nct_id', 'Unknown')} - "
            f"{signal.get('signal_type', 'Unknown')}:**"
        )

        lines.append(
            f"   {signal.get('summary', 'No summary available.')}"
        )

        lines.append(
            f"   Confidence: "
            f"{signal.get('confidence', 0.0):.2f} | "
            f"Agent: {signal.get('agent', 'unknown')}"
        )

        evidence = signal.get("evidence", [])

        lines.append(
            "   Evidence: "
            + (
                json.dumps(evidence, default=str)
                if evidence
                else "No supporting evidence supplied."
            )
        )

        lines.append("")

    lines.append(
        f"**AGENTS ACTIVATED:** "
        f"{', '.join(agents_activated)}"
    )

    lines.append(
        f"**RECORDED ERRORS:** {len(error_log or [])}"
    )

    lines.append(
        "\n*Brief generated without LLM assistance. "
        "Verify the supporting evidence before acting.*"
    )

    return "\n".join(lines)
